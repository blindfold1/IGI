class Command(BaseCommand):
    help = 'Добавляет реальные ветеринарные термины в FAQ'

    def handle(self, *args, **kwargs):
        for question, answer in TERMS:
            FAQ.objects.get_or_create(
                question=question,
                defaults={
                    'answer': answer,
                    'added_at': timezone.now().date()
                }
            )
        self.stdout.write(self.style.SUCCESS('Ветеринарные термины успешно добавлены в FAQ.')) 